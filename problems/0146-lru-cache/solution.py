class Node:
    def __init__(self, key=None, val=None):
        self.key = key
        self.val = val
        self.prev = None
        self.next = None

class LRUCache:
    def __init__(self, capacity: int):
        self.capacity = capacity
        self.cache = {}
        self.head = Node()
        self.tail = Node()
        self.head.next = self.tail
        self.tail.prev = self.head
        self.count = 0
    
    def remove(self, node):
        prev_node = node.prev
        next_node = node.next
        prev_node.next = next_node
        next_node.prev = prev_node
    
    def add(self, node):
        prev_node = self.tail.prev
        prev_node.next = node
        node.prev = prev_node
        node.next = self.tail
        self.tail.prev = node

    def get(self, key: int) -> int:
        if key in self.cache:
            node = self.cache[key]
            self.remove(node)
            self.add(node)
            return node.val
        else:
            return -1

    def put(self, key: int, value: int) -> None:
        if key in self.cache:
            # If key exists, remove the old node
            self.remove(self.cache[key])
            self.count -= 1
        
        elif self.count >= self.capacity:
            # Remove the LRU element
            lru = self.head.next
            self.remove(lru)
            del self.cache[lru.key]
            self.count -= 1

        # Add new node to the cache
        new_node = Node(key, value)
        self.add(new_node)
        self.cache[key] = new_node
        self.count += 1

